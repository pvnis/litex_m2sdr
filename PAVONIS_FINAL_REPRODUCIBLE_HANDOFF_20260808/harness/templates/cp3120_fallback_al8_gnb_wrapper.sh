  [[ "${PAVONIS_MSG3_CONRES_MAX_SLOT_OFFSET+set}" != set ]]
  [[ "${PAVONIS_MSG3_CONRES_SLOT_REBASE_TRACE_LIMIT+set}" != set ]]
  printf 'CP3120_EFFECTIVE_FALLBACK_DL_DCI_AGGR_LEV=%s\n' "$PAVONIS_GNB_FALLBACK_DL_DCI_AGGR_LEV"
  printf 'CP3120_EFFECTIVE_MSG3_CONRES_SLOT_REBASE=unset\n'
  printf 'CP3120_GNB_WRAPPER_ENV_PROBE=PASS\n'
  exit 0
fi

exec "$REAL_GNB" "$@"
