CP3120_NON_PRACH_UL_RX_CFO_HZ=0
CP3120_DYNAMIC_TRACE_LIMIT=256
CP3120_PUSCH_CSI_TRACE=1
CP3120_PUSCH_EVM_DIAGNOSTIC=1
CP3120_PUXCH_ORDER_TRACE=1
CP3120_MSG3_PATH_TRACE=1
CP3120_MSG3_PATH_TRACE_LIMIT=1024
CP3120_MSG3_CONRES_SLOT_REBASE_FROM_NON_PRACH=0
CP3120_FALLBACK_DL_DCI_AGGR_LEV=8
CP3120_GNB_WRAPPER_PROBE=PASS
EOF
  exit 0
fi

export PAVONIS_NON_PRACH_UL_RX_OFFSET_COMMIT_ON_UPPER_ACCEPT=1
export PAVONIS_NON_PRACH_UL_RX_OFFSET_EDGE_LATTICE_PERIOD_SAMPLES=823
export PAVONIS_NON_PRACH_UL_RX_OFFSET_EDGE_LATTICE_ANCHOR_SAMPLES=-138
export PAVONIS_NON_PRACH_UL_RX_OFFSET_EDGE_LATTICE_CANONICAL_SAMPLES=-6722
export PAVONIS_NON_PRACH_UL_RX_CFO_HZ=0
export PAVONIS_NON_PRACH_UL_RX_OFFSET_TRACE_LIMIT=256
export PAVONIS_PUSCH_CSI_TRACE=1
export PAVONIS_PUSCH_CSI_TRACE_LIMIT=256
export PAVONIS_PUSCH_EVM_DIAGNOSTIC=1
export PAVONIS_PUXCH_ORDER_TRACE=1
export PAVONIS_PUXCH_ORDER_TRACE_LIMIT=500
export PAVONIS_PUXCH_ORDER_TRACE_LATE_ARM=1
export PAVONIS_MSG3_PATH_TRACE=1
export PAVONIS_MSG3_PATH_TRACE_LIMIT=1024
export PAVONIS_GNB_FALLBACK_DL_DCI_AGGR_LEV=8

unset PAVONIS_MSG3_CONRES_SLOT_REBASE_FROM_NON_PRACH
