REAL_GNB_SHA=90a5db019d52b3f893572d96a8338eae67a81b1e4169e8eb12c4afab20375f8a

[[ "$(sha256sum "$REAL_GNB" | awk '{print $1}')" == "$REAL_GNB_SHA" ]]

if [[ "${PAVONIS_CP3120_GNB_WRAPPER_PROBE:-0}" == 1 ]]; then
  cat <<'EOF'
CP3120_REAL_GNB_SHA=90a5db019d52b3f893572d96a8338eae67a81b1e4169e8eb12c4afab20375f8a
CP3120_CONTEXT_EDGE_TRANSPORT=1
CP3120_COMMIT_ON_UPPER_ACCEPT=1
