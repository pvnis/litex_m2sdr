  local stamp="$1"
  local result_dir="$2"
  shift 2
  exec env \
    "${common_env[@]}" \
    PAVONIS_CP3219_UE_TX_GUARD_SAMPLES=56000 \
    PAVONIS_CP3219_GNB_PRACH_TIMING_COMPENSATION_SAMPLES=126564 \
