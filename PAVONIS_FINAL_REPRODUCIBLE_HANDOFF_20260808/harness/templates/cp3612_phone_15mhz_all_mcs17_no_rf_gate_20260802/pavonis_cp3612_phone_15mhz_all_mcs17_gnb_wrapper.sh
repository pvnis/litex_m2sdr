#!/usr/bin/env bash
set -euo pipefail

REAL_GNB=@REMOTE_HOME@/pavonis_cp3597_msg4_geometry_trace_gnb/gnb
REAL_GNB_SHA=1154351c334e8916d268b6e7531d1183efb8b872d4c22fbdd9da89c4585d409a
INNER=@REMOTE_HOME@/pavonis_cp3594_phone_15mhz_1x1_map0_gnb_wrapper.sh
INNER_SHA=c0349256efb0329660f9e5b1e0c4a495f489516f791424b93c91d83ad2a8ecd7

[[ "$(sha256sum "$REAL_GNB" | awk '{print $1}')" == "$REAL_GNB_SHA" ]]
[[ "$(sha256sum "$INNER" | awk '{print $1}')" == "$INNER_SHA" ]]

if [[ "${PAVONIS_CP3612_GNB_WRAPPER_PROBE:-0}" == 1 ]]; then
  printf 'CP3612_REAL_GNB_SHA=%s\n' "$REAL_GNB_SHA"
  printf 'CP3612_INNER_WRAPPER_SHA=%s\n' "$INNER_SHA"
  printf 'CP3612_SELECTOR_ENABLE=1\n'
  printf 'CP3612_SELECTOR_MCS_A=17\n'
  printf 'CP3612_SELECTOR_MCS_B=17\n'
  printf 'CP3612_SELECTOR_PERIOD_GRANTS=1\n'
  printf 'CP3612_SELECTOR_TRACE_LIMIT=512\n'
  printf 'CP3612_GNB_WRAPPER_PROBE=PASS\n'
  exit 0
fi

if [[ "${PAVONIS_CP3612_GNB_WRAPPER_ENV_PROBE:-0}" == 1 ]]; then
  env \
    PAVONIS_CP3594_REAL_GNB="$REAL_GNB" \
    PAVONIS_CP3594_REAL_GNB_SHA="$REAL_GNB_SHA" \
    PAVONIS_CP3594_GNB_WRAPPER_ENV_PROBE=1 \
    "$INNER"
  printf 'CP3612_EFFECTIVE_SELECTOR_ENABLE=1\n'
  printf 'CP3612_EFFECTIVE_SELECTOR_MCS_A=17\n'
  printf 'CP3612_EFFECTIVE_SELECTOR_MCS_B=17\n'
  printf 'CP3612_EFFECTIVE_SELECTOR_TRACE_LIMIT=512\n'
  printf 'CP3612_GNB_WRAPPER_ENV_PROBE=PASS\n'
  exit 0
fi

printf 'PAVONIS_CP3612_PHONE_15MHZ_ALL_MCS17_GNB_WRAPPER_ACTIVE binary_sha=%s selector_enable=1 mcs_a=17 mcs_b=17 period=1 trace_limit=512\n' \
  "$REAL_GNB_SHA"

exec env \
  PAVONIS_CP3594_REAL_GNB="$REAL_GNB" \
  PAVONIS_CP3594_REAL_GNB_SHA="$REAL_GNB_SHA" \
  PAVONIS_DL_MCS_AB_ENABLE=1 \
  PAVONIS_DL_MCS_AB_MCS_A=17 \
  PAVONIS_DL_MCS_AB_MCS_B=17 \
  PAVONIS_DL_MCS_AB_PERIOD_GRANTS=1 \
  PAVONIS_DL_MCS_AB_TRACE_LIMIT=512 \
  "$INNER" "$@"
